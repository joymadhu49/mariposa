// A first time visitor with a keyboard, in the real time loop (no stepping helpers): quick key presses must all count.
// Run it against a built file or the live site:  node tools/realtime.mjs [file-or-url]   (BROWSER=webkit for Safari's engine)
import { launch } from './lib.mjs';
import path from 'node:path';
import { root } from './lib.mjs';
const target = process.argv[2] || 'dist/mariposa.html';
const url = /^https?:/.test(target) ? target : 'file://' + path.resolve(root, target);
const { browser, page, logs } = await launch({ width: 1280, height: 720, manual: false });
let fails = 0;
const ok = (name, cond, extra = '') => { console.log((cond ? 'PASS ' : 'FAIL ') + name + (extra ? '  ' + extra : '')); if (!cond) fails++; };
await page.goto(url, { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__g && window.__g.ready, null, { timeout: 120000 });
await page.waitForTimeout(2500);
const info = () => page.evaluate(() => __g.debugInfo());
let s = await info();
ok('boots to the title screen', s.state === 'title', s.state);
await page.keyboard.press('Enter'); // down and up back to back, the way a fast tap arrives
await page.waitForTimeout(2200);
s = await info();
ok('Enter starts the game', s.state === 'play', s.state);
const a = await info();
await page.keyboard.down('KeyW');
await page.waitForTimeout(2200);
await page.keyboard.up('KeyW');
const b = await info();
ok('W flies forward', Math.hypot(b.x - a.x, b.z - a.z) > 4, `moved ${Math.hypot(b.x - a.x, b.z - a.z).toFixed(1)} m`);
await page.keyboard.press('KeyM');
await page.waitForTimeout(900);
s = await info();
ok('M opens the map', s.state === 'pause', s.state);
await page.keyboard.press('Escape');
await page.waitForTimeout(900);
s = await info();
ok('Esc closes it again', s.state === 'play', s.state);
await page.keyboard.press('KeyP');
await page.waitForTimeout(900);
s = await info();
ok('P opens photo mode', s.state === 'photo', s.state);
await page.keyboard.press('Escape');
await page.waitForTimeout(900);
s = await info();
ok('Esc leaves photo mode', s.state === 'play', s.state);
const fps0 = await page.evaluate(() => __g.frames), t0 = Date.now();
await page.waitForTimeout(2000);
const fps = ((await page.evaluate(() => __g.frames)) - fps0) / ((Date.now() - t0) / 1000);
ok('runs at a steady frame rate', fps > 24, `${fps.toFixed(0)} fps`);
const errs = logs.filter((l) => /error|pageerror/i.test(l));
ok('no console errors', errs.length === 0, errs.slice(0, 3).join(' | '));
console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
await browser.close();
process.exit(fails ? 1 : 0);
